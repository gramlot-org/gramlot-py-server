import {pathToFileURL} from 'node:url';
const [entry,url,output]=process.argv.slice(2);
if(!output)throw new Error('Usage: PLAYWRIGHT_ENTRY HOST_URL OUTPUT_DIR');
const {chromium,webkit}=await import(pathToFileURL(entry));
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir(output,{recursive:true});
for(const [name,engine] of Object.entries({chromium,webkit})){
 const browser=await engine.launch(name==='chromium'?{args:['--enable-unsafe-swiftshader']}:{});
 try{
  const page=await browser.newPage({viewport:{width:1450,height:1150}}),errors=[];
  page.setDefaultTimeout(30000);page.on('pageerror',e=>{errors.push(e.message);console.log(e.stack)});
  await page.goto(`${url.replace(/\/$/,'')}/australian_geography`);
  await page.waitForFunction(()=>window.gramlot?.data.getItem('sales.count')===8);
  const pane=page.locator('#geography-pane'),view=page.locator('#geography-pane-view');
  await pane.getByRole('button',{name:'Chart settings'}).click();
  await page.locator('#geography-pane-mapLabelMode').selectOption('name');
  await pane.getByRole('button',{name:'Chart settings'}).click();
  await view.getByText('Tasmania',{exact:true}).click();
  await page.waitForFunction(()=>window.gramlot.data.getItem('sales.state')==='TAS'&&!window.gramlot.data.getItem('loading'));
  await pane.getByRole('button',{name:'Chart settings'}).click();
  await page.locator('#geography-pane-mapLabelMode').selectOption('value');
  await pane.getByRole('button',{name:'Chart settings'}).click();
  await page.waitForTimeout(600);
  const labels=await view.locator('svg text').allTextContents();assert.ok(labels.some(t=>/^\d.*[MK]$/i.test(t)));
  const colors=await view.locator('svg path').evaluateAll(paths=>[...new Set(paths.map(p=>p.getAttribute('fill')).filter(f=>f?.startsWith('rgb')))]);
  assert.ok(colors.length>3);console.log(name,'ECharts graduated colors',colors.length,'numeric labels',labels.filter(t=>/^\d.*[MK]$/i.test(t)).length);
  const rect=await view.boundingBox();await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.55);await page.mouse.wheel(0,-550);await page.waitForTimeout(500);
  assert.equal(await view.getByRole('alert').isVisible(),false);
  await page.screenshot({path:`${output}/${name}-2d.png`,fullPage:true});
  await pane.getByRole('button',{name:'Chart settings'}).click();
  await page.locator('#geography-pane-engine').selectOption('plotly');await view.locator('.js-plotly-plot').waitFor();await page.waitForTimeout(800);
  const visible=await view.locator('.scattergeo text').evaluateAll(nodes=>nodes.filter(n=>n.style.visibility!=='hidden').length);assert.ok(visible>0);
  const plot=view.locator('.js-plotly-plot');
  assert.equal(await plot.evaluate(el=>el.data[1].z.length),93);
  const plotBounds=await plot.boundingBox();await page.mouse.move(plotBounds.x+plotBounds.width*.5,plotBounds.y+plotBounds.height*.65);await page.mouse.wheel(0,-400);await page.waitForTimeout(500);
  assert.equal(await plot.evaluate(el=>el.data[1].z.length),93);
  console.log(name,'Plotly matched values and visible numeric labels',visible);
  await page.locator('#geography-pane-engine').selectOption('echarts');
  await page.locator('#geography-pane-chartType').selectOption('mapBar3D');
  await view.locator('canvas').first().waitFor();await page.waitForTimeout(1500);
  const alert=await view.getByRole('alert').isVisible();if(alert)console.log(await view.getByRole('alert').innerText());assert.equal(alert,false);
  assert.equal(await page.locator('#geography-pane-engine option[value=plotly]').evaluate(el=>el.hidden),true);
  await pane.getByRole('menuitem',{name:'Choose measures',exact:true}).click();
  await page.getByRole('menuitemcheckbox',{name:'Revenue per customer',exact:true}).click();
  await page.waitForTimeout(900);
  assert.equal(await page.evaluate(()=>window.gramlot.data.getItem('mapChart.valueFields')),'revenue,per_customer');
  await pane.getByRole('button',{name:'Chart settings'}).click();await page.waitForTimeout(500);
  await page.screenshot({path:`${output}/${name}-3d.png`,fullPage:true});
  await pane.getByRole('button',{name:'Chart settings'}).click();
  await page.locator('#geography-pane-mapBarScale').selectOption('extent');await page.waitForTimeout(700);
  assert.equal(await view.getByRole('alert').isVisible(),false);
  assert.equal(await page.evaluate(()=>window.gramlot.data.getItem('mapChart.mapBarScale')),'extent');
  await page.locator('#geography-pane-chartType').selectOption('map');await view.locator('svg').waitFor();
  await page.locator('#geo-home').click();await page.waitForFunction(()=>window.gramlot.data.getItem('sales.state')===''&&!window.gramlot.data.getItem('loading'));
  assert.equal(await page.locator('#geography-pane-mapLabelMode').inputValue(),'value');
  assert.deepEqual(errors,[]);console.log(name,'3D bars, two measures, scale choice and return passed');
 }finally{await browser.close();}
}
